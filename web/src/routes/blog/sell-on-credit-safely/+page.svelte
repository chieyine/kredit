	<h1>How to sell on credit and protect your money</h1>
	<p class="lede">Before goods leave your shop, write down these five things. They can prevent most payment arguments.</p>

	<h2>1. The exact amount owed</h2>
	<p>Do not write “about ₦500,000.” Write the full amount, including delivery costs if the customer must pay them.</p>

	<h2>2. The exact payment date</h2>
	<p>Choose one calendar date. “End of the month” can mean different things to different people.</p>

	<h2>3. Any extra time you will allow</h2>
	<p>A customer may need a few more days. Agree the number of extra days now, and state what happens when that time ends.</p>

	<h2>4. Proof of delivery</h2>
	<p>Record the goods, quantity, date and person who received them. Add a photo or delivery note when useful.</p>

	<h2>5. What happens if payment is late</h2>
	<p>Agree on the steps before the sale: reminders first, extra time next, then an automatic debit only if the customer already gave permission.</p>

