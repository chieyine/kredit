	<h1>What to do when a customer pays late</h1>
	<p class="lede">Nobody enjoys chasing payment. A clear, fair process helps you collect what is owed without damaging a good customer relationship.</p>

	<h2>Take these steps in order</h2>
	<ol>
		<li><strong>Send friendly reminders.</strong> Use WhatsApp, where your customer already reads messages.</li>
		<li><strong>Allow the extra time you agreed.</strong> Keep the date clear and do not change the rules halfway through.</li>
		<li><strong>Record any bank transfer or cash payment.</strong> Your customer reports it and you confirm it before the balance changes.</li>
		<li><strong>Try an automatic debit only as the last step.</strong> This can happen only after the extra time ends and only if the customer gave permission.</li>
	</ol>

	<h2>Why a clear process works</h2>
	<p>Your customer knows the steps from the start. Nobody is surprised, and you do not need angry calls or threats to make the next step clear.</p>

	<h2>Protect both sides</h2>
	<p>An automatic debit must never take more than is owed. It must pause for any amount being questioned and give the customer a receipt when payment succeeds.</p>

