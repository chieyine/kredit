	<h1>Why credit sales turn into arguments</h1>
	<p class="lede">Most arguments are not about whether money is owed. They start because the goods, date or amount were not clearly recorded.</p>

	<h2>When both sides remember differently</h2>
	<p>A carton is missing. The goods arrived late. The customer says you promised a better grade. Without a clear record, a business problem quickly becomes personal.</p>

	<h2>Keep proof as part of every sale</h2>
	<p>You are not preparing for a fight. You are helping both sides remember the same facts:</p>
	<ul>
		<li><strong>What you sent</strong> — the goods and quantity that left your shop.</li>
		<li><strong>What the customer received</strong> — confirmed by the customer.</li>
		<li><strong>What both sides accepted</strong> — a deal that cannot be quietly changed later.</li>
	</ul>

	<h2>Many problems become easier to solve</h2>
	<p>When both sides see the same record, many arguments end quickly. If they do not, each side can add their explanation and proof. Automatic debit pauses for the amount being questioned.</p>

